// Drives the clone through the same states as reference/screens (stage-1 run on the original)
// and saves reference/clone/<same name>.png. Usage: node clone-shots.mjs [--only=14,15,22] [url]
import { chromium, devices } from 'playwright';
import { mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const args = process.argv.slice(2);
const only = args.find((a) => a.startsWith('--only='))?.slice(7).split(',');
const APP = args.find((a) => !a.startsWith('--')) ?? 'http://localhost:5173/';
const OUT = fileURLToPath(new URL('../../reference/clone/', import.meta.url));
mkdirSync(OUT, { recursive: true });

const browser = await chromium.launch();
const ctx = await browser.newContext({ ...devices['Pixel 7'], viewport: { width: 390, height: 844 }, deviceScaleFactor: 2, locale: 'ru-RU', reducedMotion: 'reduce' });
// The original has no voice input: hide it (no Speech API → no «Говорить» block) to keep the comparison fair.
await ctx.addInitScript(() => { window.SpeechRecognition = undefined; window.webkitSpeechRecognition = undefined; });
const page = await ctx.newPage();
await page.goto(APP);
await page.evaluate(() => localStorage.clear());
await page.reload();
await page.evaluate(() => document.fonts.ready);

const shot = async (name) => {
  if (only && !only.some((p) => name.startsWith(p))) return;
  await page.waitForTimeout(150);
  await page.screenshot({ path: `${OUT}${name}.png` });
  console.log('shot', name);
};
const btn = (name) => page.getByRole('button', { name, exact: true });
const preset = (name) => page.getByRole('button', { name: new RegExp(`^${name} \\+\\d+$`) });
const group = (name) => page.getByRole('group', { name, exact: true });
const plus = async (g, n = 1) => { for (let i = 0; i < n; i++) await group(g).getByRole('button', { name: 'Больше' }).click(); };
const minus = async (g, n = 1) => { for (let i = 0; i < n; i++) await group(g).getByRole('button', { name: 'Меньше' }).click(); };
const menu = () => btn('Открыть меню навигации').click();
const closeDrawer = () => page.mouse.click(370, 600);
const name = (i) => page.getByLabel(`Введите имя ${i}`);

